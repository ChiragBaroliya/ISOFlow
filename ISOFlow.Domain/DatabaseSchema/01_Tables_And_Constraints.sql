-- 19. Management Decisions Table
CREATE TABLE management_decisions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_review_id INT NOT NULL REFERENCES management_reviews(id) ON DELETE CASCADE,
    decision_text TEXT NOT NULL,
    owner VARCHAR(150) NOT NULL,
    due_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    improvement_id INT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'Approved',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata')
);

-- 20. Improvements Table
CREATE TABLE improvements (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    title VARCHAR(250) NOT NULL,
    current_state TEXT NULL,
    future_state TEXT NULL,
    source INT NOT NULL DEFAULT 0, -- 0=AuditFinding, 1=RiskAssessment, 2=Incident, 3=ManagementReview, etc.
    expected_benefit TEXT NULL,
    owner VARCHAR(150) NOT NULL,
    status INT NOT NULL DEFAULT 0, -- 0=Identified, 1=Approved, 2=InProgress, 3=Completed, 4=Verified
    related_review_id INT NULL,
    related_finding_id INT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 21. Notifications Table
CREATE TABLE notifications (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(250) NOT NULL,
    message TEXT NOT NULL,
    category VARCHAR(50) NOT NULL DEFAULT 'General',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    link_url VARCHAR(500) NULL
);

-- 22. Audit Logs Table
CREATE TABLE audit_logs (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp" TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    "user" VARCHAR(150) NOT NULL,
    action VARCHAR(100) NOT NULL,
    module VARCHAR(100) NOT NULL,
    entity_id VARCHAR(50) NOT NULL,
    details TEXT NULL
);


-- 14. Audits Table
CREATE TABLE audits (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    title VARCHAR(250) NOT NULL,
    standard_id INT NULL REFERENCES standards(id) ON DELETE SET NULL,
    lead_auditor VARCHAR(150) NOT NULL,
    start_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    end_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status INT NOT NULL DEFAULT 0, -- 0=Planned, 1=Scheduled, 2=InProgress, 3=Reporting, 4=Completed
    completion_percentage INT NOT NULL DEFAULT 0,
    scope TEXT NULL,
    check_list_control_ids_json TEXT NULL,
    finding_ids_json TEXT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 15. Findings Table
CREATE TABLE findings (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    title VARCHAR(250) NOT NULL,
    audit_id INT NULL REFERENCES audits(id) ON DELETE SET NULL,
    requirement_id INT NULL,
    control_id INT NULL,
    severity INT NOT NULL DEFAULT 1, -- 0=OFI, 1=Observation, 2=MinorNC, 3=MajorNC
    status INT NOT NULL DEFAULT 0,   -- 0=Open, 1=InAnalysis, 2=CapaAssigned, 3=Resolved, 4=Closed
    description TEXT NULL,
    root_cause TEXT NULL,
    identified_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    auditor VARCHAR(150) NOT NULL,
    capa_id INT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 16. CAPAs Table
CREATE TABLE capas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    finding_id INT NULL,
    title VARCHAR(250) NOT NULL,
    root_cause TEXT NULL,
    corrective_action TEXT NULL,
    owner VARCHAR(150) NOT NULL,
    due_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status INT NOT NULL DEFAULT 0, -- 0=Draft, 1=InAnalysis, 2=ActionPlanApproved, 3=InProgress, 4=VerificationPending, 5=Closed
    effectiveness_verification TEXT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 17. Capa Action Items Table
CREATE TABLE capa_action_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capa_id INT NOT NULL REFERENCES capas(id) ON DELETE CASCADE,
    title VARCHAR(250) NOT NULL,
    assigned_to VARCHAR(150) NOT NULL,
    due_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata')

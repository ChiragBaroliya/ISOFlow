-- 1. Organizations Table
CREATE TABLE organizations (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    industry VARCHAR(100) NOT NULL,
    employees INT NOT NULL DEFAULT 0,
    locations_json TEXT NULL,
    primary_standard VARCHAR(100) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'Active',
    compliance_percentage DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    contact_email VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 2. Users Table
CREATE TABLE users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id INT NULL REFERENCES organizations(id) ON DELETE SET NULL,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL DEFAULT 'Test@123',
    system_role INT NOT NULL DEFAULT 2, -- 0=SuperAdmin, 1=Admin, 2=User
    role VARCHAR(100) NOT NULL,
    department VARCHAR(100) NOT NULL,
    location VARCHAR(100) NOT NULL,
    avatar_url VARCHAR(500) NULL,
    phone VARCHAR(50) NULL,
    bio TEXT NULL,
    reset_token VARCHAR(50) NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 3. Standards Table
CREATE TABLE standards (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    revision VARCHAR(50) NOT NULL,
    description TEXT NULL,
    requirement_count INT NOT NULL DEFAULT 0,
    compliance_percentage DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    is_preseeded BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(50) NOT NULL DEFAULT 'Active',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 4. Requirements Table
CREATE TABLE requirements (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard_id INT NOT NULL REFERENCES standards(id) ON DELETE CASCADE,
    clause VARCHAR(50) NOT NULL,
    title VARCHAR(250) NOT NULL,
    description TEXT NULL,
    category VARCHAR(100) NOT NULL,
    compliance_percentage DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    related_control_ids_json TEXT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 5. Controls Table
CREATE TABLE controls (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(250) NOT NULL,
    requirement_id INT NULL,
    standard_id INT NULL REFERENCES standards(id) ON DELETE SET NULL,
    category VARCHAR(100) NOT NULL,
    description TEXT NULL,
    status INT NOT NULL DEFAULT 0, -- 0=NotImplemented, 1=InDevelopment, 2=Implemented, 3=Tested, 4=NeedsReview
    owner VARCHAR(150) NOT NULL,
    compliance_percentage DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    is_applicable BOOLEAN NOT NULL DEFAULT TRUE,
    justification TEXT NULL,
    related_requirement_ids_json TEXT NULL,
    related_risk_ids_json TEXT NULL,
    related_treatment_ids_json TEXT NULL,
    related_policy_ids_json TEXT NULL,
    related_process_ids_json TEXT NULL,
    related_task_ids_json TEXT NULL,
    related_evidence_ids_json TEXT NULL,
    related_audit_ids_json TEXT NULL,
    related_finding_ids_json TEXT NULL,
    related_capa_ids_json TEXT NULL,
    related_management_review_ids_json TEXT NULL,
    related_improvement_ids_json TEXT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 6. Risks Table
CREATE TABLE risks (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(250) NOT NULL,
    description TEXT NULL,
    asset VARCHAR(150) NOT NULL,
    department VARCHAR(100) NOT NULL,
    owner VARCHAR(150) NOT NULL,
    likelihood INT NOT NULL DEFAULT 1, -- 1=Rare, 2=Unlikely, 3=Possible, 4=Likely, 5=AlmostCertain
    impact INT NOT NULL DEFAULT 1,     -- 1=Negligible, 2=Minor, 3=Moderate, 4=Major, 5=Critical
    treatment_id INT NULL,
    control_id INT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'Open',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 7. Risk Treatments Table
CREATE TABLE risk_treatments (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_id INT NOT NULL REFERENCES risks(id) ON DELETE CASCADE,
    option VARCHAR(50) NOT NULL DEFAULT 'Mitigate',
    treatment_plan TEXT NOT NULL,
    owner VARCHAR(150) NOT NULL,
    target_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    residual_likelihood INT NOT NULL DEFAULT 1,
    residual_impact INT NOT NULL DEFAULT 1,
    status VARCHAR(50) NOT NULL DEFAULT 'In Progress',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 8. Policies Table
CREATE TABLE policies (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(250) NOT NULL,
    version VARCHAR(50) NOT NULL DEFAULT '1.0',
    owner VARCHAR(150) NOT NULL,
    effective_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    next_review_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'Active',
    file_path VARCHAR(500) NULL,
    linked_control_ids_json TEXT NULL,
    linked_process_ids_json TEXT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
);

-- 9. Processes Table
CREATE TABLE processes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(250) NOT NULL,
    category VARCHAR(100) NOT NULL,
    owner VARCHAR(150) NOT NULL,
    description TEXT NULL,
    version VARCHAR(50) NOT NULL DEFAULT '1.0',
    status VARCHAR(50) NOT NULL DEFAULT 'Active',
    steps_json TEXT NULL,

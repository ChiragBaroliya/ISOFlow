-- 18. Management Reviews Table
CREATE TABLE management_reviews (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    title VARCHAR(250) NOT NULL,
    period VARCHAR(50) NOT NULL DEFAULT 'Q4 2026',
    review_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    chair_person VARCHAR(150) NOT NULL,
    attendees_json TEXT NULL,
    summary TEXT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'Completed',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NULL
